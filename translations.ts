export const TRANSLATIONS: Record<Language, TranslationType> = { en, zh };

/** Replace the first `%s` in a template. */
export const format = (template: string, value: string | number): string =>
  template.replace('%s', String(value));

export const resolveTranslations = (language: Language): TranslationType =>
  TRANSLATIONS[language] ?? TRANSLATIONS.en;
